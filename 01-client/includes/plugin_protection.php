// ── Plugin protection ("lock") ───────────────────────────────
// Deactivating, uninstalling or uploading a plugin can take features (and data) away from a live business, and the
// buttons sit one click apart. So those actions are LOCKED by default and enforced on the server, not just hidden:
// the admin has to unlock changes on purpose — by re-entering their password — and the unlock expires by itself.
// Activating a plugin is never locked (it only adds things and is still license-checked).
const SLATE_PLUGINS_UNLOCK_SECONDS = 900;   // 15 minutes
if (!function_exists('slate_plugins_unlocked_until')) {
    /** Unix time the current unlock ends, or 0 when changes are locked. Bound to the admin who unlocked. */
    function slate_plugins_unlocked_until(): int {
        $until = (int)($_SESSION['plugins_unlocked_until'] ?? 0);
        $uid   = (int)($_SESSION['plugins_unlocked_uid'] ?? 0);
        return ($until > time() && $uid === (int)Auth::userId()) ? $until : 0;
    }
    function slate_plugins_locked(): bool { return slate_plugins_unlocked_until() === 0; }
}

