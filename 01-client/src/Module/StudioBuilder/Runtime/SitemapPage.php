<?php
/**
 * Kohevo Studio — the readable sitemap page.
 *
 * A person who opens `/sitemap.xml` in a browser sees a Kohevo-branded list of the site's pages (path, address,
 * last change) instead of a raw XML tree. Crawlers keep getting the XML: the runtime chooses by the request's
 * `Accept` header (a browser asks for `text/html` first) and `?format=xml` always returns the XML.
 *
 * The page is built from the same entries as the XML, every value escaped, with no script and no external
 * resource, so it adds no tenant data of its own and nothing a visitor can inject.
 */

declare(strict_types=1);

namespace Slate\Module\StudioBuilder\Runtime;

final class SitemapPage
{
    /**
     * Whether a request's `Accept` header asks for a web page rather than XML: `text/html` is listed and comes
     * before any XML type. A browser sends `text/html,application/xhtml+xml,application/xml;q=0.9,*&#47;*;q=0.8`; a
     * crawler sends `*&#47;*` or an XML type.
     */
    public static function prefersHtml(?string $accept): bool
    {
        if ($accept === null || $accept === '') {
            return false;
        }
        $htmlAt = null;
        $xmlAt = null;
        foreach (explode(',', strtolower(substr($accept, 0, 400))) as $i => $part) {
            $type = trim(explode(';', $part, 2)[0]);
            if ($type === 'text/html' && $htmlAt === null) {
                $htmlAt = $i;
            }
            if (($type === 'application/xml' || $type === 'text/xml') && $xmlAt === null) {
                $xmlAt = $i;
            }
        }
        return $htmlAt !== null && ($xmlAt === null || $htmlAt < $xmlAt);
    }

    /**
     * @param list<array{loc: string, lastmod: ?string}> $entries
     * @param string $siteName the site's name for the heading
     * @param string $homeUrl the absolute URL of the home page, to mark its row
     * @param bool $hidden the site is set to noindex (Site & SEO), so it lists no page on purpose
     */
    public static function html(array $entries, string $siteName, string $homeUrl, bool $hidden = false): string
    {
        $e = static fn(string $v): string => htmlspecialchars($v, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');

        $latest = '';
        foreach ($entries as $entry) {
            $d = (string) ($entry['lastmod'] ?? '');
            if ($d > $latest) {
                $latest = $d;
            }
        }

        $rows = '';
        foreach ($entries as $i => $entry) {
            $loc = (string) $entry['loc'];
            $path = (string) (parse_url($loc, PHP_URL_PATH) ?: '/');
            $isHome = rtrim($loc, '/') === rtrim($homeUrl, '/');
            $rows .= '<tr><td class="n">' . ($i + 1) . '</td><td><a href="' . $e($loc) . '"><span class="path">' . $e($path)
                . ($isHome ? '<span class="home">Home</span>' : '') . '</span><span class="full">' . $e($loc) . '</span></a></td>'
                . '<td class="d hide-s">' . ($entry['lastmod'] ? $e((string) $entry['lastmod']) : '—') . "</td></tr>\n";
        }
        $table = $rows === ''
            ? '<div class="empty">' . ($hidden
                ? 'This site is hidden from search engines (Site &amp; SEO › Search robots policy is set to noindex), so no page is listed. Allow indexing there to list every published page.'
                : 'No pages are published yet.') . '</div>'
            : '<table><thead><tr><th>#</th><th>Page</th><th class="hide-s">Last changed</th></tr></thead><tbody>' . $rows . '</tbody></table>';

        return '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
            . '<meta name="robots" content="noindex"><title>Sitemap · ' . $e($siteName) . '</title><style>' . self::css() . '</style></head><body><div class="wrap">'
            . '<div class="brand"><div class="logo"><svg viewBox="0 0 24 24" fill="none" stroke="#fff" stroke-width="2.6" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M7 4v16"/><path d="M18 5L9.5 12.5 18 20"/></svg></div>'
            . '<div><b>Kohevo Studio</b><span>' . $e($siteName) . ' · XML sitemap</span></div></div>'
            . '<h1>Sitemap</h1><p class="lead">Every published page that search engines are invited to index. This is the readable view; crawlers receive the same address as plain XML.</p>'
            . '<div class="stats"><div class="stat"><strong>' . count($entries) . '</strong><span>Pages listed</span></div>'
            . '<div class="stat"><strong>' . ($latest !== '' ? $e($latest) : '—') . '</strong><span>Latest change</span></div></div>'
            . '<div class="card">' . $table . '</div>'
            . '<footer><span>Generated by Kohevo Studio</span><a href="sitemap.xml?format=xml">View the raw XML</a></footer>'
            . '</div></body></html>';
    }

    private static function css(): string
    {
        return ':root{--bg:#0b0b10;--panel:#14141c;--line:#262633;--text:#e9e9f1;--muted:#8d8da3;--accent:#8b5cf6;--soft:rgba(139,92,246,.14)}'
            . '@media (prefers-color-scheme:light){:root{--bg:#f6f6fa;--panel:#fff;--line:#e3e3ee;--text:#16161d;--muted:#6b6b80;--accent:#6d3fe0;--soft:rgba(109,63,224,.1)}}'
            . '*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--text);font:15px/1.5 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}'
            . '.wrap{max-width:980px;margin:0 auto;padding:32px 20px 56px}.brand{display:flex;align-items:center;gap:12px;margin-bottom:28px}'
            . '.logo{width:40px;height:40px;border-radius:11px;background:linear-gradient(135deg,#a78bfa,#7c3aed);display:flex;align-items:center;justify-content:center}.logo svg{width:22px;height:22px}'
            . '.brand b{font-size:15px;letter-spacing:.02em}.brand span{display:block;color:var(--muted);font-size:12px}'
            . 'h1{font-size:28px;margin:0 0 6px;letter-spacing:-.01em}.lead{color:var(--muted);margin:0 0 22px}'
            . '.stats{display:flex;flex-wrap:wrap;gap:12px;margin:0 0 22px}.stat{background:var(--panel);border:1px solid var(--line);border-radius:12px;padding:12px 16px;min-width:140px}'
            . '.stat strong{display:block;font-size:22px;line-height:1.2}.stat span{color:var(--muted);font-size:12px;text-transform:uppercase;letter-spacing:.06em}'
            . '.card{background:var(--panel);border:1px solid var(--line);border-radius:14px;overflow:hidden}table{width:100%;border-collapse:collapse}'
            . 'th{text-align:left;font-size:11px;text-transform:uppercase;letter-spacing:.08em;color:var(--muted);padding:12px 16px;border-bottom:1px solid var(--line);background:rgba(127,127,160,.06)}'
            . 'td{padding:13px 16px;border-bottom:1px solid var(--line);vertical-align:top}tr:last-child td{border-bottom:0}tr:hover td{background:var(--soft)}'
            . 'td.n{color:var(--muted);width:44px;font-variant-numeric:tabular-nums}td.d{white-space:nowrap;color:var(--muted);font-variant-numeric:tabular-nums}'
            . 'a{color:var(--accent);text-decoration:none;word-break:break-all}a:hover{text-decoration:underline}'
            . '.path{display:block;font-weight:600;color:var(--text)}.full{display:block;font-size:12.5px;font-family:ui-monospace,SFMono-Regular,Menlo,monospace}'
            . '.home{display:inline-block;margin-left:8px;font-size:10.5px;font-weight:600;letter-spacing:.06em;text-transform:uppercase;color:var(--accent);background:var(--soft);padding:2px 7px;border-radius:99px;vertical-align:1px}'
            . '.empty{padding:36px;text-align:center;color:var(--muted)}footer{margin-top:22px;color:var(--muted);font-size:12.5px;display:flex;justify-content:space-between;gap:12px;flex-wrap:wrap}'
            . '@media (max-width:640px){.hide-s{display:none}td,th{padding:11px 12px}h1{font-size:23px}}';
    }
}
